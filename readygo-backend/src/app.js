import express from "express";
import cors from "cors";
import helmet from "helmet";
import morgan from "morgan";
import rateLimit from "express-rate-limit";
import { requestContext } from "./middleware/requestContext.js";
import { notFound, errorHandler } from "./middleware/errorHandler.js";
import authRoutes from "./modules/auth/auth.routes.js";
import driverAuthRoutes from "./modules/driver/driverAuth.routes.js";
import uploadRoutes from "./modules/uploads/uploads.routes.js";
import userRoutes from "./modules/users/users.routes.js";
import fareRoutes from "./modules/fares/fares.routes.js";
import rideRoutes from "./modules/rides/rides.routes.js";
import driverRoutes from "./modules/driver/driver.routes.js";
import ratingRoutes from "./modules/ratings/ratings.routes.js";
import performanceRoutes from "./modules/performance/performance.routes.js";
import safetyRoutes from "./modules/safety/safety.routes.js";
import paymentRoutes from "./modules/payments/payments.routes.js";
import adminRoutes from "./modules/admin/admin.routes.js";
import driverWalletRoutes from "./modules/driver/driverWallet.routes.js";
import driverSupportRoutes from "./modules/driver/driverSupport.routes.js";
import driverReferralRoutes from "./modules/driver/driverReferral.routes.js";
import driverNotificationRoutes from "./modules/driver/driverNotification.routes.js";

const app=express();
app.set("trust proxy", 1);
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({origin:process.env.CORS_ORIGIN?.split(",")||true}));
app.use(express.json({limit:"1mb"}));
app.use(express.urlencoded({extended:false,limit:"1mb"}));
app.use(requestContext);
if(process.env.NODE_ENV!=="test")app.use(morgan("combined"));
app.use("/api",rateLimit({windowMs:15*60*1000,limit:1000,standardHeaders:true,legacyHeaders:false,validate:{xForwardedForHeader:false}}));
app.get("/health",(req,res)=>res.json({success:true,data:{status:"ok",service:"readygo-backend",timestamp:new Date().toISOString()}}));
const prefixes = Array.from(new Set([process.env.API_PREFIX || "/api/v1", "/api"]));
for (const p of prefixes) {
  app.use(`${p}/auth`, authRoutes);
  app.use(`${p}/driver/auth`, driverAuthRoutes);
  app.use(`${p}/uploads`, uploadRoutes);
  app.use(`${p}/upload`, uploadRoutes);
  app.use(`${p}`, userRoutes);
  app.use(`${p}`, fareRoutes);
  app.use(`${p}`, rideRoutes);
  app.use(`${p}`, driverRoutes);
  app.use(`${p}`, ratingRoutes);
  app.use(`${p}`, performanceRoutes);
  app.use(`${p}`, safetyRoutes);
  app.use(`${p}`, paymentRoutes);
  app.use(`${p}`, adminRoutes);
  app.use(`${p}`, driverWalletRoutes);
  app.use(`${p}`, driverSupportRoutes);
  app.use(`${p}`, driverReferralRoutes);
  app.use(`${p}`, driverNotificationRoutes);
}
app.use(notFound);
app.use(errorHandler);
export default app;
