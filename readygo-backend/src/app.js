import express from "express";
import cors from "cors";
import helmet from "helmet";
import morgan from "morgan";
import rateLimit from "express-rate-limit";
import { requestContext } from "./middleware/requestContext.js";
import { notFound, errorHandler } from "./middleware/errorHandler.js";
import authRoutes from "./modules/auth/auth.routes.js";
import userRoutes from "./modules/users/users.routes.js";
import fareRoutes from "./modules/fares/fares.routes.js";
import rideRoutes from "./modules/rides/rides.routes.js";
import driverRoutes from "./modules/driver/driver.routes.js";
import ratingRoutes from "./modules/ratings/ratings.routes.js";
import performanceRoutes from "./modules/performance/performance.routes.js";
import safetyRoutes from "./modules/safety/safety.routes.js";
import paymentRoutes from "./modules/payments/payments.routes.js";
import adminRoutes from "./modules/admin/admin.routes.js";

const app=express();
app.disable("x-powered-by");
app.use(helmet());
app.use(cors({origin:process.env.CORS_ORIGIN?.split(",")||true}));
app.use(express.json({limit:"1mb"}));
app.use(express.urlencoded({extended:false,limit:"1mb"}));
app.use(requestContext);
if(process.env.NODE_ENV!=="test")app.use(morgan("combined"));
app.use("/api",rateLimit({windowMs:15*60*1000,limit:300,standardHeaders:true,legacyHeaders:false}));
app.get("/health",(req,res)=>res.json({success:true,data:{status:"ok",service:"readygo-backend",timestamp:new Date().toISOString()}}));
const prefix=process.env.API_PREFIX||"/api/v1";
app.use(`${prefix}/auth`,authRoutes);
app.use(`${prefix}`,userRoutes);
app.use(`${prefix}`,fareRoutes);
app.use(`${prefix}`,rideRoutes);
app.use(`${prefix}`,driverRoutes);
app.use(`${prefix}`,ratingRoutes);
app.use(`${prefix}`,performanceRoutes);
app.use(`${prefix}`,safetyRoutes);
app.use(`${prefix}`,paymentRoutes);
app.use(`${prefix}`,adminRoutes);
app.use(notFound);
app.use(errorHandler);
export default app;
